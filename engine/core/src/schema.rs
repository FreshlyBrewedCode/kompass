/// A generated file: its name in the output directory and its contents.
pub type File = (&'static str, String);

fn schema<T: JsonSchema>() -> String {
    let s = SchemaSettings::draft2020_12()
        .into_generator()
        .into_root_schema_for::<T>();
    let mut out = serde_json::to_string_pretty(&s).expect("a schema serialises");
    out.push('\n');
    out
}

const HEADER: &str =
    "// Generated by `kompass schema --write` from the Rust types in engine/core (profile.rs,
// catalogue.rs, route.rs, explain.rs, overrides.rs, tradeoffs.rs, cost.rs, presets.rs). Do not
// edit: change the Rust types and regenerate (`bun run gen:engine`); `cargo test` fails when this
// file is stale.
";

/// One TypeScript declaration with its doc comment, exported.
fn decl<T: TS + 'static>(cfg: &Config) -> String {
    let mut s = String::new();
    if let Some(docs) = T::docs() {
        s.push_str(&docs);
    }
    s.push_str("export ");
    s.push_str(&T::decl(cfg));
    s.push('\n');
    s
}

