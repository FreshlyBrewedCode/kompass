"""`docs/edges-parquet.md`: the prose is hand-written, the column and enum tables between the markers
are generated from `schema.py`. A test fails when the page is stale; `kompass-pipeline docs --write`
regenerates it."""

from __future__ import annotations

import re
from pathlib import Path

from . import schema

BEGIN, END = "<!-- schema:begin (generated by `kompass-pipeline docs --write`) -->", "<!-- schema:end -->"
PAGE = Path(__file__).resolve().parents[3] / "docs" / "edges-parquet.md"
_BLOCK = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)


def generated_block() -> str:
    return f"{BEGIN}\n\n{schema.render_columns_markdown()}\n\n{END}"


def render(page_text: str) -> str:
    if not _BLOCK.search(page_text):
        raise ValueError("docs page has no schema markers")
    return _BLOCK.sub(lambda _: generated_block(), page_text)


def main(write: bool = False, page: Path = PAGE) -> int:
    text = page.read_text()
    new = render(text)
    if new == text:
        return 0
    if write:
        page.write_text(new)
        print(f"updated {page}")
        return 0
    print(f"{page} is stale: run `kompass-pipeline docs --write`")
    return 1
